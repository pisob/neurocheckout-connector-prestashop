    public static function trans(string $key, array $params = [], ?string $locale = null): string
    {
        $lang = self::normalizeLocale($locale ?: self::resolveLocale());
        $catalog = self::CATALOG[$lang] ?? self::CATALOG[self::FALLBACK_LOCALE];
        $message = $catalog[$key] ?? self::CATALOG[self::FALLBACK_LOCALE][$key] ?? $key;

        if (empty($params)) {
            return $message;
        }

        $replacements = [];
        foreach ($params as $name => $value) {
            $replacements['{' . $name . '}'] = (string) $value;
        }

        return strtr($message, $replacements);
    }

