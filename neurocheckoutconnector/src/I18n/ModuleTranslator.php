    public static function transForLanguage(Language $language, string $key, array $params = []): string
    {
        $locale = '';
        if (!empty($language->locale)) {
            $locale = (string) $language->locale;
        } elseif (!empty($language->language_code)) {
            $locale = (string) $language->language_code;
        } elseif (!empty($language->iso_code)) {
            $locale = (string) $language->iso_code;
        }

        return self::trans($key, $params, $locale);
    }

    private static function resolveLocale(): string
    {
        $context = Context::getContext();
        if ($context && isset($context->language) && $context->language) {
            $language = $context->language;
            if (!empty($language->locale)) {
                return (string) $language->locale;
            }
            if (!empty($language->language_code)) {
                return (string) $language->language_code;
            }
            if (!empty($language->iso_code)) {
                return (string) $language->iso_code;
            }
        }

        return self::FALLBACK_LOCALE;
    }

    private static function normalizeLocale(string $locale): string
    {
        $locale = strtolower(str_replace('_', '-', trim($locale)));
        if ($locale === '') {
            return self::FALLBACK_LOCALE;
        }

        $parts = explode('-', $locale, 2);
        return $parts[0] !== '' ? $parts[0] : self::FALLBACK_LOCALE;
    }
